import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import React, { act } from '../../admin/node_modules/react/index.js';
const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost:5173/blogs' });
globalThis.window = dom.window; globalThis.document = dom.window.document; globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const { createRoot } = await import('../../admin/node_modules/react-dom/client.js');
const server = await createServer({ root: fileURLToPath(new URL('../../admin', import.meta.url)), configFile: false, plugins: [react()], server: { middlewareMode: true }, appType: 'custom' });
try {
  const { default: BlogManager } = await server.ssrLoadModule('/BlogManager.jsx');
  const posts = [...JSON.parse(await readFile(new URL('../../backend/content/jaipurBlogs.json', import.meta.url), 'utf8')), ...JSON.parse(await readFile(new URL('../../backend/content/serviceBlogs.json', import.meta.url), 'utf8'))].map((post, index) => ({ ...post, _id: String(index), createdAt: '2026-11-03', updatedAt: '2026-11-03' }));
  let edited, updated, refreshed = 0, deleted = 0;
  const root = createRoot(document.getElementById('root'));
  await act(async () => root.render(React.createElement(BlogManager, { items: posts, websiteBase: 'https://chalakgo.com', add() {}, edit: post => edited = post, patch: async (post, patch) => updated = { post, patch }, refresh: async () => refreshed++, remove: async () => { deleted++; return false; } })));
  assert.equal(document.querySelectorAll('.bm-table tbody > tr').length, 30);
  await act(async () => document.querySelector('.bm-text-button').click());
  assert.ok(document.querySelector('.bm-preview-content').textContent.includes('Choose the right kind of booking'));
  assert.ok(document.querySelector('.bm-seo-summary').textContent.includes(posts[0].seoTitle));
  await act(async () => document.querySelector('.bm-preview-heading button').click());
  assert.equal(edited.content, posts[0].content);
  assert.equal(edited.coverImage, posts[0].coverImage);
  await act(async () => document.querySelector('[aria-label^="Save as draft"]').click());
  assert.deepEqual(updated.patch, { isPublished: false });
  await act(async () => document.querySelector('[aria-label^="Set noindex"]').click());
  assert.deepEqual(updated.patch, { noindex: true });
  await act(async () => document.querySelector('.bm-delete').click());
  assert.equal(deleted, 1);
  assert.ok(!document.querySelector('.bm-results').textContent.includes('Article deleted'));
  await act(async () => [...document.querySelectorAll('button')].find(button => button.textContent === 'Refresh list').click());
  assert.equal(refreshed, 1);
  const input = document.querySelector('input[type=search]');
  await act(async () => { Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(input, 'no-such-article-search'); input.dispatchEvent(new window.Event('input', { bubbles: true })); });
  assert.ok(document.querySelector('.bm-empty').textContent.includes('No matching articles'));
  await act(async () => root.unmount());
  console.log('PASS: 30 admin records, full content/SEO preview, edit data, publication and noindex mutations, refresh, cancelled deletion and search.');
} finally { await server.close(); dom.window.close(); }
